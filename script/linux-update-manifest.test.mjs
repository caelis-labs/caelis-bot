import test from 'node:test';
import assert from 'node:assert/strict';
import {generateKeyPairSync,createHash} from 'node:crypto';
import {mkdtempSync,mkdirSync,writeFileSync,readFileSync,rmSync,symlinkSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {create,collect,signManifest,verifyManifest} from './linux-update-manifest.mjs';
const sha=b=>createHash('sha256').update(b).digest('hex');
test('Linux manifest binds complete bundle, test identity and exact signing key',t=>{
 const root=mkdtempSync(join(tmpdir(),'caelis-update-contract-'));
 t.after(()=>rmSync(root,{recursive:true,force:true}));
 mkdirSync(join(root,'Helpers'));mkdirSync(join(root,'Resources'));
 const binary=Buffer.alloc(64);binary.set(Buffer.from('7f454c460201','hex'));binary.writeUInt16LE(183,18);
 for(const name of ['caelisbot','Helpers/caelis'])writeFileSync(join(root,name),binary,{mode:0o755});
 const marker={version:'v0.72.2',commit:'b'.repeat(40),targets:{'linux-arm64':{binary_sha256:sha(binary)}}};
 for(const [name,bytes]of Object.entries({'Resources/Caelis-Runtime.json':JSON.stringify(marker),'Resources/Caelis-Runtime-LICENSE':'runtime license',LICENSE:'license'}))writeFileSync(join(root,name),bytes,{mode:0o644});
 for(const name of ['ASSET-LICENSE.md','Resources/Caelis-Protocol-LICENSE','Resources/OpenClaw-Weixin-LICENSE','Resources/Go-QRCode-LICENSE'])writeFileSync(join(root,name),'license fixture',{mode:0o644});
 const archive=join(tmpdir(),root.split('/').pop()+'.tar.gz');t.after(()=>rmSync(archive,{force:true}));writeFileSync(archive,'test archive bytes');
 const manifest=create(root,archive,'0.17.1-qa.1','a'.repeat(40),'linux-arm64','qa');
 assert.equal(manifest.runtime.sha256,sha(binary));assert.equal(manifest.sha256,sha(readFileSync(archive)));
 assert.throws(()=>create(root,archive,'0.17.1-qa.1','a'.repeat(40),'linux-arm64','release'));
 assert.throws(()=>create(root,archive,'0.17.1-qa.1','a'.repeat(40),'linux-amd64','qa'));
 symlinkSync('/etc/passwd',join(root,'unexpected'));assert.throws(()=>collect(root));rmSync(join(root,'unexpected'));
 const {publicKey,privateKey}=generateKeyPairSync('ed25519');
 const pub=join(root,'pub'),priv=join(root,'priv'),file=join(root,'manifest.json');
 writeFileSync(pub,publicKey.export({format:'der',type:'spki'}).subarray(-32).toString('base64'));
 writeFileSync(priv,privateKey.export({format:'pem',type:'pkcs8'}),{mode:0o600});
 writeFileSync(file,JSON.stringify(manifest));
 signManifest(file,priv,pub);assert.deepEqual(verifyManifest(file,pub),manifest);
 writeFileSync(file,JSON.stringify({...manifest,version:'0.17.1-qa.2'}));assert.throws(()=>verifyManifest(file,pub));
 rmSync(file+'.sig');writeFileSync(file,JSON.stringify({...manifest,buildKind:'release'}));
 assert.throws(()=>signManifest(file,priv,pub),/reviewed embedded release key/);
});
