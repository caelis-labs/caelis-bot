import {createHash} from 'node:crypto';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const manifest=JSON.parse(readFileSync('protocol/caelis/manifest.json','utf8'));
const hash=path=>createHash('sha256').update(readFileSync(path)).digest('hex');
assert.match(manifest.commit,/^[0-9a-f]{40}$/);
const runtime=JSON.parse(readFileSync('resources/caelis-runtime/release.json','utf8'));
assert.match(runtime.commit,/^[0-9a-f]{40}$/);
assert.equal(manifest.commit,runtime.commit,'Caelis protocol and runtime release source differ');
assert.equal(manifest.version,runtime.version,'Caelis protocol and runtime release versions differ');
assert.equal(manifest.contractOverlayCommit,undefined,'Unified Core protocol must not carry a second overlay');
assert.equal(hash('protocol/caelis/openapi.json'),manifest.schemaSha256,'Caelis public schema drift');
assert.equal(hash('internal/backend/caelis/wire/control_v1.gen.go'),manifest.wireSha256,'Caelis generated wire drift');
const schemaText=readFileSync('protocol/caelis/openapi.json','utf8');
const contract=JSON.parse(schemaText);
assert.ok(Object.keys(contract.paths).every(path=>!/^\/(?:api\/control\/v1\/)?applications?(?:\/|$)/.test(path)), 'Retired Application route remains');
assert.doesNotMatch(schemaText,/\bapplication-[a-z-]+-v\d+\b/,'Retired Application capability remains');
const schemas=contract.components.schemas;
assert.ok(Object.keys(schemas).every(name=>!name.startsWith('Application')), 'Retired Application wire type remains');
const profile=schemas.SessionProfile;
const patch=schemas.SessionConfigurationPatch;
for(const field of ['mcp_servers','skill_dirs','skill_roots']){
  assert.ok(profile.properties[field],`Caelis creation profile lacks ${field}`);
  assert.ok(patch.properties[field],`Caelis configuration patch lacks ${field}`);
  assert.equal(patch.properties[field]['x-go-omitzero'],true,`Caelis patch cannot distinguish omitted from [] for ${field}`);
}
assert.equal(schemas.CreateSessionRequest.allOf[1].properties.profile.$ref,'#/components/schemas/SessionProfile');
assert.equal(schemas.SessionConfiguration.properties.profile.$ref,'#/components/schemas/SessionProfile');
assert.ok(readFileSync('protocol/caelis/LICENSE','utf8').length>100);
console.log(`Caelis public protocol ${manifest.commit.slice(0,12)}.`);
