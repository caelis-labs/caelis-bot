import {readFileSync, writeFileSync} from 'node:fs';
import {ExpressFormat, SkillGenerator} from '@a2ui/agent';
import {chatCatalog} from '../frontend/src/chat-a2ui-catalog.ts';
import {comparison, collection, draft} from './a2ui-chat-examples.mjs';

const target = new URL('../internal/botskills/skills/bot-core/references/a2ui-chat.md', import.meta.url);
const format = new ExpressFormat([chatCatalog], {version: 'v1.0', allowedMessages: ['createSurface']});
const generated = new SkillGenerator(format).generateSkill().content;
// The upstream grammar lists events and surface directives even for a catalog
// without action components. Keep the remaining official text verbatim.
const sections = generated.split(/\n(?=\d+\. |## )/);
const unsupported = /^(8\. Action events|12\. Required actions|13\. Surface targeting)/;
if (sections.filter(section => unsupported.test(section)).length !== 3) throw Error('Review upstream Express rules before regenerating');
const rules = sections.filter(section => !unsupported.test(section)).join('\n')
 .replace(/^   root = ComponentB.*Event.*\n/m, '');

const examples = [['Compare details in tabs', comparison], ['Repeat supplied records', collection], ['Edit and validate a local draft', draft]];
const local = `# Present results in desktop chat

Give the important facts, recommendation and next step in Markdown. Add one compact block when choosing tabs, reading grouped records or editing a small draft makes the result easier to use. Put each sentinel at column one on its own line, with blank lines separating the block from prose. Keep each block independent.

Tabs, selections and edits stay in the current view. For a mock form use sample values, short labels and one or two relevant checks. Use a Slider with steps for bounded numeric choices. TextField produces text, including its number variant. Ask the user in ordinary chat when a choice or value needs to reach you. Use ordinary Markdown for actions, approvals, messages intended for text channels, and simple answers. Do not ask for credentials in a draft.

Use the component and function signatures below. Assign initial data with \`$/path = value\` as shown in the examples. Use double-quoted, single-line strings, and up to 12 items per list or group. The host accepts one \`root\` tree of up to 40 components per block. Use local bindings and checks. Omit events, surface directives, explicit updates, media and standalone calls.

## Desktop chat examples

${examples.map(([title, body]) => '### '+title+'\n\n```text\n<a2ui>\n'+body+'\n</a2ui>\n```').join('\n\n')}

## Protocol and catalog reference

<!-- Generated by @a2ui/agent SkillGenerator from the desktop catalog derived from @a2ui/web_core Basic v1.0. Apache-2.0. Bot omits three unsupported rules and the event example. As installed, the license is in ../assets/A2UI-LICENSE. -->

`;
const result = local + rules.trimEnd() + '\n';
if (process.argv.includes('--check')) {
 if (readFileSync(target, 'utf8') !== result) throw Error('Stale desktop chat A2UI reference. Run node script/generate-chat-a2ui-reference.mjs');
} else {
 writeFileSync(target, result);
}
