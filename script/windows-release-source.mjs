import {execFileSync} from 'node:child_process';
import {appendFileSync} from 'node:fs';
import {windowsRelease} from './windows-version.mjs';
const tag=process.env.WINDOWS_TAG,release=windowsRelease(tag);
const git=args=>execFileSync('git',args,{encoding:'utf8'}).trim();
const sha=git(['rev-parse',`${tag}^{commit}`]);
if(!/^[a-f0-9]{40}$/.test(sha))throw Error('Invalid tag source');
git(['merge-base','--is-ancestor',sha,'HEAD']);
const pkg=JSON.parse(git(['show',`${sha}:package.json`]));
if(release.base!==pkg.version)throw Error('Windows tag base differs from the selected main source');
appendFileSync(process.env.GITHUB_OUTPUT,`sha=${sha}\nrevision=${release.revision}\nchannel=${release.channel}\n`);
